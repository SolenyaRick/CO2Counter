#!/usr/bin/env python3
"""Keeps style.css on the design system: one type scale, one radius scale,
one spacing scale and a small set of ink colours for text.

    python3 scripts/snap-design.py        # snap style.css in place
    python3 scripts/snap-design.py --check  # list anything off the scale

Snaps px values in font-size (and the size in `font:`), border-radius,
margin, padding and gap to the nearest step, and neutral brown/grey or dark
green text colours to the nearest ink. Brand colours (gold, clay, the light
text on dark panels) and anything inside calc() or env() are left alone.
The generated dark-mode block is skipped: run build-dark-css.py after.
"""
import colorsys
import re
import sys
from pathlib import Path

CSS = Path(__file__).resolve().parent.parent / "style.css"
START = "/* ===== dark mode: generated by scripts/build-dark-css.py, do not edit ===== */"
END = "/* ===== end of generated dark mode ===== */"

# Type: 12 13 15 16 18 20 24 28 34 40 48 64 84 (16 stays for form fields,
# so iPhones don't zoom in).
TYPE = [12, 13, 15, 16, 18, 20, 24, 28, 34, 40, 48, 64, 84]
TYPE_MAP = {14: 15, 14.4: 15, 14.5: 15, 17: 18, 19: 18, 21: 20, 22: 20, 23: 24, 25: 24, 26: 28, 30: 28, 32: 34, 36: 34, 38: 40, 42: 40, 44: 48, 46: 48, 56: 64, 72: 64, 76: 84}
# Corners: 6 for small tags, 12 for buttons and fields, 16 for rows,
# 20 for cards, 28 for big panels and sheets, and full pills.
RADII = [6, 12, 16, 20, 28]
# Spacing: a 4px grid, with 2/6/10 for tight insides.
SPACE = [2, 4, 6, 8, 10, 12, 16, 20, 24, 28, 32, 40, 48, 56, 64, 80, 96]
# Text inks.
INKS = ["#2E2A22", "#4A453A", "#5C5649", "#6B6455", "#8A8273"]
GREEN_DARK, GREEN = "#22331F", "#3F5B3A"


def nearest(v, scale, prefer_up=False):
    best = min(scale, key=lambda s: (abs(s - v), -s if prefer_up else s))
    return best


def snap_type(v):
    if v in TYPE_MAP:
        return TYPE_MAP[v]
    if v <= 12:
        return 12 if v >= 9.5 else v  # tiny print stays as it is
    if v > 84:
        return v
    return nearest(v, TYPE, prefer_up=v < 16)


def snap_radius(v):
    if v >= 40:
        return 999  # every pill uses the same value
    if v <= 3:
        return v
    return nearest(v, RADII, prefer_up=True)


def snap_space(v):
    if v <= 1 or v > 120:
        return v
    return nearest(v, SPACE)


def fmt(n):
    return ("%g" % n) + "px"


def px_sub(value, fn, rem=True):
    if "calc(" in value or "env(" in value or "clamp(" in value or "min(" in value or "max(" in value:
        return value
    value = re.sub(r"(?<![\w.-])(\d+(?:\.\d+)?)px", lambda m: fmt(fn(float(m.group(1)))), value)
    # rem steps become px on the same scale (1rem = 16px)
    if rem:
        value = re.sub(r"(?<![\w-])(\d*\.?\d+)rem\b", lambda m: fmt(fn(float(m.group(1)) * 16)), value)
    return value


def rgb_of(c):
    c = c.strip().lower()
    if c.startswith("#"):
        h = c[1:]
        if len(h) == 3:
            h = "".join(x * 2 for x in h)
        if len(h) != 6:
            return None
        return tuple(int(h[i:i + 2], 16) / 255 for i in (0, 2, 4))
    m = re.match(r"rgb\(\s*(\d+)\s*,\s*(\d+)\s*,\s*(\d+)\s*\)$", c)
    if m:
        return tuple(int(x) / 255 for x in m.groups())
    return None


def lum(rgb):
    return colorsys.rgb_to_hls(*rgb)[1]


def snap_ink(c):
    rgb = rgb_of(c)
    if not rgb:
        return c
    h, l, s = colorsys.rgb_to_hls(*rgb)
    if l > 0.62:
        return c  # light text on dark panels
    green = 0.22 <= h <= 0.42 and s >= 0.12
    if green:
        return GREEN_DARK if l < 0.17 else GREEN
    neutral = s < 0.22 and (0.04 <= h <= 0.2 or s < 0.08)
    if not neutral:
        return c  # brand colours: gold, clay, blue
    return min(INKS, key=lambda i: abs(lum(rgb_of(i)) - l))


DECL = re.compile(r"(?<![\w-])(font-size|font|border-radius|border-(?:top|bottom)-(?:left|right)-radius|margin(?:-(?:top|bottom|left|right|block|inline)(?:-start|-end)?)?|padding(?:-(?:top|bottom|left|right|block|inline)(?:-start|-end)?)?|gap|row-gap|column-gap|color)\s*:\s*([^;{}]+)")


def snap_decl(m):
    prop, value = m.group(1), m.group(2)
    imp = ""
    if "!important" in value:
        value, imp = value.replace("!important", "").rstrip(), " !important"
    v = value
    if prop == "font-size":
        v = px_sub(value, snap_type)
    elif prop == "font":
        v = re.sub(r"(?<![\w.-])(\d+(?:\.\d+)?)px(?=(?:/\S+)?\s+[\w\"'-])", lambda x: fmt(snap_type(float(x.group(1)))), value)
    elif "radius" in prop:
        v = px_sub(value, snap_radius)
    elif prop == "color":
        v = re.sub(r"#[0-9a-fA-F]{3,6}\b|rgb\([^)]*\)", lambda x: snap_ink(x.group(0)), value)
    else:
        v = px_sub(value, snap_space)
    if v == value:
        return m.group(0)
    return prop + ": " + v.strip() + imp


def main():
    css = CSS.read_text()
    a, b = css.find(START), css.find(END)
    head, gen, tail = (css[:a], css[a:b], css[b:]) if a >= 0 else (css, "", "")
    new_head = DECL.sub(snap_decl, head)
    new_tail = DECL.sub(snap_decl, tail)
    if "--check" in sys.argv:
        changed = sum(1 for x, y in zip(head.split("\n"), new_head.split("\n")) if x != y) + sum(1 for x, y in zip(tail.split("\n"), new_tail.split("\n")) if x != y)
        print("lines off the design system:", changed)
        return 1 if changed else 0
    CSS.write_text(new_head + gen + new_tail)
    print("snapped")
    return 0


if __name__ == "__main__":
    sys.exit(main())
