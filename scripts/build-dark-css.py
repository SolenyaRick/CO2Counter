#!/usr/bin/env python3
"""Builds the dark mode for style.css.

The app's colours are written straight into thousands of rules, so instead of
keeping a hand-made copy in step, this reads style.css and writes a dark
version of every colour rule into a block at the end of the file, inside
@media (prefers-color-scheme: dark). It runs again whenever style.css changes:

    python3 scripts/build-dark-css.py

How colours change:
- light surfaces (cream cards, the page) become deep greens, keeping their
  order: what's lighter in the light theme is lighter in the dark one too
- dark text becomes light text, keeping its hue (greens stay green)
- faint dark tints and borders become faint light ones
- mid-tones (the brand greens, terracotta, the tile colours) stay as they are
- gold things (medals, the "I've switched" button...) stay gold: see KEEP
Hand-tuned dark rules go after the generated block (see DARK_TUNING in style.css).
"""
import colorsys
import re
import sys
from pathlib import Path

CSS = Path(__file__).resolve().parent.parent / "style.css"
START = "/* ===== dark mode: generated by scripts/build-dark-css.py, do not edit ===== */"
END = "/* ===== end of generated dark mode ===== */"

# Rules left exactly as they are: gold and honey accents that read well on dark.
KEEP = re.compile(r"btn-honey|hb3-win-btn|hb3-medal|hb3-pin|hb3-big-medal|hb3-top\b|hb3-spot|hb3-go\b|hb3-badges li\.got|hb3-party|plan-go|acc-support|fr-btn\.honey|you-here|hb3-chip\.kg|intro-why|hb3-lvchip|tab-ink")

COLOR_RE = re.compile(r"#[0-9a-fA-F]{8}\b|#[0-9a-fA-F]{6}\b|#[0-9a-fA-F]{3}\b|rgba?\([^)]*\)|\bwhite\b|\bblack\b")
BG_PROPS = {"background", "background-color", "background-image"}
FG_PROPS = {"color", "fill", "stroke", "-webkit-text-fill-color", "caret-color", "text-decoration-color", "accent-color"}
LINE_PROPS = {"border", "border-color", "border-top", "border-bottom", "border-left", "border-right", "border-top-color",
              "border-bottom-color", "border-left-color", "border-right-color", "outline", "outline-color", "box-shadow"}


def parse_color(s):
    s = s.strip()
    if s == "white":
        return (1, 1, 1, 1)
    if s == "black":
        return (0, 0, 0, 1)
    if s.startswith("#"):
        h = s[1:]
        if len(h) == 3:
            h = "".join(c * 2 for c in h)
        a = int(h[6:8], 16) / 255 if len(h) == 8 else 1
        return (int(h[0:2], 16) / 255, int(h[2:4], 16) / 255, int(h[4:6], 16) / 255, a)
    nums = [x.strip() for x in s[s.index("(") + 1:-1].replace("/", ",").split(",")]
    vals = []
    for i, x in enumerate(nums[:4]):
        if x.endswith("%"):
            vals.append(float(x[:-1]) / 100)
        elif i < 3:
            vals.append(float(x) / 255)
        else:
            vals.append(float(x))
    if len(vals) == 3:
        vals.append(1)
    return tuple(vals)


def fmt(r, g, b, a):
    r, g, b = [max(0, min(255, round(v * 255))) for v in (r, g, b)]
    if a >= 0.999:
        return "#%02x%02x%02x" % (r, g, b)
    return "rgba(%d, %d, %d, %s)" % (r, g, b, ("%.3f" % a).rstrip("0").rstrip("."))


def remap(col, kind):
    r, g, b, a = parse_color(col)
    h, l, s = colorsys.rgb_to_hls(r, g, b)
    if kind == "bg":
        if a < 0.6 and l < 0.3:          # a faint dark tint -> a faint light tint
            return fmt(*colorsys.hls_to_rgb(h, 0.92, s * 0.5), a)
        if l >= 0.82:                    # cream surfaces -> deep green, order kept
            nl, ns = 0.105 + (l - 0.82) / 0.18 * 0.075, min(s, 0.18)
            return fmt(*colorsys.hls_to_rgb(0.28 if s < 0.25 else h, nl, ns), a)
        if l >= 0.55:                    # light tints -> dark tints of the same hue
            return fmt(*colorsys.hls_to_rgb(h, 0.17 + (l - 0.55) * 0.25, min(s, 0.35)), a)
        return None
    if kind == "fg":
        if l < 0.45:                     # dark text -> light text, same hue
            return fmt(*colorsys.hls_to_rgb(h, 0.9 - l * 0.4, min(s, 0.45)), a)
        return None
    if kind == "line":
        if l < 0.3 and a < 0.7:          # faint dark lines -> faint light lines
            return fmt(*colorsys.hls_to_rgb(h, 0.92, s * 0.4), a)
        if l >= 0.82 and a < 0.999:      # glassy light edges -> faint light edges
            return fmt(*colorsys.hls_to_rgb(h, 0.92, s * 0.3), min(a, 0.12))
        if l >= 0.82:
            return fmt(*colorsys.hls_to_rgb(0.28, 0.2, 0.15), a)
        return None
    return None


ROOT_VARS = {}
VAR_RE = re.compile(r"var\((--[\w-]+)\)")


def resolve_vars(value):
    """Swap var(--x) for its colour, so text and lines can be lightened even
    when the same variable also paints the green buttons."""
    return VAR_RE.sub(lambda m: ROOT_VARS.get(m.group(1), m.group(0)) if COLOR_RE.fullmatch(ROOT_VARS.get(m.group(1), "") or "") else m.group(0), value)


def map_value(prop, value):
    kind = "bg" if prop in BG_PROPS else "fg" if prop in FG_PROPS else "line" if prop in LINE_PROPS else None
    if prop.startswith("--"):            # custom properties: only the page's surfaces and ink
        n = prop.lower()
        if not re.fullmatch(r"--(bg|fg|card|glass|glass-strong|glass-border|muted|muted-fg|border|input|surface[\w-]*)", n):
            return None
        kind = "fg" if re.search(r"fg|text|ink", n) else "line" if re.search(r"border|input", n) else "bg"
        if "shadow" in n or "font" in n or "display" in n or "mono" in n:
            return None
    if not kind:
        return None
    if kind in ("fg", "line", "bg") and "var(" in value and not prop.startswith("--"):
        resolved = resolve_vars(value)
        if resolved != value:
            m = map_value(prop, resolved)
            return m
    changed = False

    def sub(m):
        nonlocal changed
        try:
            new = remap(m.group(0), kind)
        except Exception:
            return m.group(0)
        if new and new != m.group(0):
            changed = True
            return new
        return m.group(0)

    if kind == "line" and prop == "box-shadow":
        # only the light rings in shadows ("0 0 0 4px #FFFCF5"), not the shadows themselves
        out = COLOR_RE.sub(lambda m: (remap(m.group(0), "bg") or m.group(0)) if parse_color(m.group(0))[3] > 0.6 and colorsys.rgb_to_hls(*parse_color(m.group(0))[:3])[1] > 0.82 else m.group(0), value)
        return out if out != value else None
    out = COLOR_RE.sub(sub, value)
    return out if changed else None


def parse(css):
    """Tiny CSS parser: a list of (selector or at-rule prelude, body) where the
    body is a declarations string or a nested list."""
    i, n, out = 0, len(css), []

    def block(i):
        items = []
        while i < n:
            while i < n and css[i] in " \t\r\n":
                i += 1
            if i >= n:
                break
            if css.startswith("/*", i):
                i = css.index("*/", i) + 2
                continue
            if css[i] == "}":
                return items, i + 1
            j = i
            while j < n and css[j] not in "{;}":
                if css.startswith("/*", j):
                    j = css.index("*/", j) + 2
                    continue
                j += 1
            if j >= n:
                break
            if css[j] == ";":            # @import / @charset
                i = j + 1
                continue
            if css[j] == "}":
                i = j
                continue
            prelude = re.sub(r"/\*.*?\*/", "", css[i:j], flags=re.S).strip()
            if prelude.startswith("@media") or prelude.startswith("@supports"):
                inner, i = block(j + 1)
                items.append((prelude, inner))
            elif prelude.startswith("@"):
                depth, k = 1, j + 1      # keyframes, font-face: skip
                while depth and k < n:
                    depth += {"{": 1, "}": -1}.get(css[k], 0)
                    k += 1
                i = k
            else:
                k = css.index("}", j)
                items.append((prelude, css[j + 1:k]))
                i = k + 1
        return items, i

    out, _ = block(0)
    return out


def decls(body):
    body = re.sub(r"/\*.*?\*/", "", body, flags=re.S)
    parts, depth, cur = [], 0, ""
    for ch in body:
        depth += {"(": 1, ")": -1}.get(ch, 0)
        if ch == ";" and depth == 0:
            parts.append(cur)
            cur = ""
        else:
            cur += ch
    parts.append(cur)
    for p in parts:
        if ":" in p:
            k, v = p.split(":", 1)
            yield k.strip().lower(), v.strip()


def emit(items, media=None):
    out = []
    for prelude, body in items:
        if isinstance(body, list):
            if "prefers-color-scheme" in prelude:
                continue
            cond = prelude[len("@media"):].strip() if prelude.startswith("@media") else None
            if prelude.startswith("@supports"):
                continue
            out += emit(body, cond if not media else media + " and " + cond)
            continue
        if KEEP.search(prelude):
            continue
        # gold buttons (painted with the honey "leaf" colour) stay gold, with dark text
        if re.search(r"background(-color)?\s*:[^;]*var\(--leaf", body):
            continue
        new = []
        for k, v in decls(body):
            imp = v.endswith("!important")
            v0 = v[: -len("!important")].strip() if imp else v
            m = map_value(k, v0)
            if m:
                new.append("%s: %s%s" % (k, m, " !important" if imp else ""))
        if new:
            out.append((media, prelude, "; ".join(new)))
    return out


def main():
    css = CSS.read_text()
    if START in css:
        a = css.index(START)
        b = css.index(END) + len(END)
        before, after = css[:a].rstrip() + "\n", css[b:]
    else:
        before, after = css.rstrip() + "\n", "\n"
    tree = parse(before)
    for prelude, body in tree:      # the page's colour variables (last one wins)
        if prelude == ":root" and isinstance(body, str):
            for k, v in decls(body):
                if k.startswith("--"):
                    ROOT_VARS[k] = v.strip()
    rules = emit(tree)
    lines = [START, ":root { color-scheme: light dark; }"]
    for media, sel, body in rules:
        cond = "(prefers-color-scheme: dark)" + (" and " + media if media else "")
        lines.append("@media %s { %s { %s; } }" % (cond, sel, body))
    lines.append(END)
    CSS.write_text(before + "\n" + "\n".join(lines) + "\n" + after.lstrip("\n"))
    print("dark rules:", len(rules))


if __name__ == "__main__":
    sys.exit(main())
